/** Same question for everyone on a given local date (YYYY-MM-DD). */
export function questionFor(day: string): { index: number; text: string } {
  const [y, m, d] = day.split("-").map(Number);
  const dayNumber = Math.floor(Date.UTC(y, m - 1, d) / 86_400_000);
  const index = ((dayNumber * 7) % QUESTIONS.length + QUESTIONS.length) % QUESTIONS.length;
  return { index, text: QUESTIONS[index] };
}
