/** Day 0 of the rotation (local date). */
const START = Date.UTC(2026, 10, 9); // 9 Nov 2026

/** Same question for everyone on a given local date (YYYY-MM-DD); steps through the list one per day. */
export function questionFor(day: string): { index: number; text: string } {
  const [y, m, d] = day.split("-").map(Number);
  const n = Math.round((Date.UTC(y, m - 1, d) - START) / 86_400_000);
  const index = ((n % QUESTIONS.length) + QUESTIONS.length) % QUESTIONS.length;
  return { index, text: QUESTIONS[index] };
}

